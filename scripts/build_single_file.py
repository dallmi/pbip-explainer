#!/usr/bin/env python3
"""Build single-file/pbip_explainer.py: the whole tool (CLI, analysis, docs, package, desktop app) in one file.

Why: on a locked-down work PC, cloning a repo or downloading a zip may not be wanted. One text file can be
opened on GitHub, copied with "Copy raw file" and pasted into a new file. Python 3.9+ standard library only.

The modules are embedded as source strings and served to Python's import system by a small finder, so the
code runs exactly as in the repo. Run after every change to skills/ or app/ (a test checks it is current):

    python3 scripts/build_single_file.py
"""
from __future__ import annotations

import hashlib
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PKG = ROOT / "skills" / "pbip-explain" / "scripts" / "pbipx"
OUT = ROOT / "single-file" / "pbip_explainer.py"

MODULE_ORDER = ["__init__", "tmdl", "dax", "mquery", "model", "report", "unpack", "analysis", "diagram", "docs",
                "query", "pack", "portfolio", "package"]

HEADER = '''#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""pbip-explainer — single-file edition {version}

Understand, document and package Power BI projects (PBIP). Everything runs on this computer.
Python 3.9 or newer, standard library only: no installs, no admin rights.

Install: create a new file named pbip_explainer.py and paste this whole text into it.

Use:
    python pbip_explainer.py                       start the desktop app in the browser (drag and drop zips)
    python pbip_explainer.py --make-launcher       write start-pbip-explainer.bat next to this file (Windows)
    python pbip_explainer.py run Report.zip --out out\\report        command line: extract + docs
    python pbip_explainer.py package out\\a out\\b --out catalog.zip   SharePoint / Agent Builder package
    python pbip_explainer.py query out\\report measure "Headcount"     look things up
    python pbip_explainer.py --help

The app keeps its results in a folder "pbip-explainer-data" next to this file.

Generated by scripts/build_single_file.py from the pbip-explainer repository. Source checksum {checksum}.
Do not edit this file by hand; change the repository and rebuild.
"""
'''

LOADER = r'''
import importlib.abc
import importlib.util
import os
import sys
from pathlib import Path


class _EmbeddedModules(importlib.abc.MetaPathFinder, importlib.abc.Loader):
    """Serves the embedded modules to Python's import system."""

    def find_spec(self, fullname, path=None, target=None):
        if fullname in _SOURCES:
            return importlib.util.spec_from_loader(fullname, self, is_package=fullname in _PACKAGES)
        return None

    def create_module(self, spec):
        return None

    def exec_module(self, module):
        name = module.__name__
        module.__file__ = __file__
        if name in _PACKAGES:
            module.__path__ = []
        code = compile(_SOURCES[name], f"<pbip-explainer:{name.replace('.', '/')}.py>", "exec")
        exec(code, module.__dict__)


def _make_launcher():
    here = Path(__file__).resolve()
    bat = here.with_name("start-pbip-explainer.bat")
    bat.write_text(
        "@echo off\r\n"
        "rem Starts pbip-explainer (local web app). Close this window to stop.\r\n"
        "cd /d \"%~dp0\"\r\n"
        "where py >nul 2>nul && (py -3 \"" + here.name + "\" %* & goto :eof)\r\n"
        "where python >nul 2>nul && (python \"" + here.name + "\" %* & goto :eof)\r\n"
        "echo Python 3.9 or newer was not found.\r\n"
        "pause\r\n", encoding="ascii")
    print(f"Wrote {bat}. Double-click it to start the app.")


CLI_COMMANDS = {"run", "extract", "docs", "query", "package"}


def main(argv=None):
    argv = list(sys.argv[1:] if argv is None else argv)
    if sys.version_info < (3, 9):
        print("Python 3.9 or newer is needed.")
        return 1
    sys.meta_path.insert(0, _EmbeddedModules())
    if argv[:1] == ["--make-launcher"]:
        _make_launcher()
        return 0
    if argv and argv[0] in CLI_COMMANDS:
        import pbip_explain_cli
        return pbip_explain_cli.main(argv)
    if argv[:1] in (["-h"], ["--help"]):
        print(__doc__)
        import pbip_explain_cli
        pbip_explain_cli.main(["--help"])
        return 0
    import pbipx_app
    pbipx_app.EMBEDDED_INDEX = _INDEX_HTML
    pbipx_app.DEFAULT_DATA_DIR = Path(__file__).resolve().with_name("pbip-explainer-data")
    return pbipx_app.main(argv)


if __name__ == "__main__":
    sys.exit(main())
'''


def sources() -> dict:
    out = {}
    for name in MODULE_ORDER:
        mod = "pbipx" if name == "__init__" else f"pbipx.{name}"
        out[mod] = (PKG / f"{name}.py").read_text(encoding="utf-8")
    out["pbip_explain_cli"] = (ROOT / "skills" / "pbip-explain" / "scripts" / "pbip_explain.py").read_text(encoding="utf-8")
    out["pbipx_app"] = (ROOT / "app" / "server.py").read_text(encoding="utf-8")
    extra = sorted(p.stem for p in PKG.glob("*.py") if p.stem not in MODULE_ORDER)
    if extra:
        raise SystemExit(f"New module(s) {extra} in pbipx: add them to MODULE_ORDER in {Path(__file__).name}.")
    return out


def build() -> str:
    src = sources()
    index = (ROOT / "app" / "static" / "index.html").read_text(encoding="utf-8")
    h = hashlib.sha256()
    for k in sorted(src):
        h.update(k.encode() + b"\0" + src[k].encode("utf-8"))
    h.update(index.encode("utf-8"))
    version = next(line.split("=")[1].strip().strip('"') for line in src["pbipx"].splitlines() if line.startswith("__version__"))
    parts = [HEADER.format(version=version, checksum=h.hexdigest()[:16]),
             "# ---------------------------------------------------------------- embedded sources\n",
             "_PACKAGES = {'pbipx'}\n", "_SOURCES = {}\n"]
    for k, v in src.items():
        parts.append(f"\n_SOURCES[{k!r}] = {v!r}\n")
    parts.append(f"\n_INDEX_HTML = {index!r}\n")
    parts.append(LOADER)
    return "".join(parts)


def main() -> int:
    text = build()
    OUT.parent.mkdir(parents=True, exist_ok=True)
    with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    print(f"wrote {OUT.relative_to(ROOT)} ({len(text.encode('utf-8')) // 1024} KB)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
